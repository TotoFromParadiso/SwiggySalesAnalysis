import pandas as pd # Used to organize, manipulate, and analyze data in tables called DataFrames.
import numpy as np # Used for numerical calculations and working with arrays and mathematical operations.
import matplotlib.pyplot as plt # Used to create graphs and charts to visualize data.
import seaborn as sns # Used to create attractive statistical charts and visualize relationships between variables.
import plotly.express as px # Used to create interactive charts and graphs that allow users to explore data.

"""Import Data"""

df = pd.read_excel("swiggy_data.xlsx")

df.head()

df.tail()

"""Meta Data"""

print("Number of Rows:", df.shape[0])

print("Number of Fields:", df.shape[1])

df.info()

df.dtypes

df.describe()

"""# KPI's

Total Sales
"""

total_sales = df["Price (INR)"].sum()
print("Total Sales (INR):", round(total_sales, 2))

"""Average Rating"""

avg_rating = df["Rating"].mean()
print("Average Rating:", round(avg_rating,2))

"""Average Order Value"""

avg_order_value = df["Price (INR)"].mean()
print("Average Order Value (INR):", round(avg_order_value, 2))

"""Ratings Count"""

ratings_count = df["Rating Count"].sum()
print("Ratings Count:", round(ratings_count, 2))

"""Total Orders"""

total_orders = df["Order Date"].count()
print("Total Orders:", round(total_orders, 2))

"""# Charts Design

Monthly Sales Trend
"""

df["Order Date"] = pd.to_datetime(df["Order Date"])

df["YearMonth"] = df["Order Date"].dt.to_period("M").astype(str)

monthly_revenue = df.groupby("YearMonth")["Price (INR)"].sum().reset_index()

plt.figure()
plt.plot(monthly_revenue["YearMonth"], monthly_revenue["Price (INR)"])
plt.xticks(rotation=45)
plt.xlabel("Month")
plt.ylabel("Total Sales (INR)")
plt.title("Monthly Sales Trend")
plt.tight_layout()
plt.show()

"""Daily Sales Trend"""

df["DayName"] = pd.to_datetime(df["Order Date"]).dt.day_name()

daily_revenue = (
    df.groupby("DayName")["Price (INR)"]
    .sum()
    .reindex(["Monday","Tuesday","Wednesday","Thursday","Friday","Saturday","Sunday"])
)

plt.figure(figsize=(10,5))
plt.bar(daily_revenue.index, daily_revenue.values)
plt.title("Daily Revenue Trend (Mon-Sun)")
plt.xlabel("Day")
plt.ylabel("Revenue (INR)")
plt.xticks(rotation=30)
plt.show()

